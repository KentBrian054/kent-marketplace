import { strict as assert } from 'node:assert';
import { readFile } from 'node:fs/promises';
const root=process.env.MARKETPLACE_TEST_URL || 'http://127.0.0.1:3188';
const check=async (path,status,opts)=>{
  const res=await fetch(root+path,opts);
  assert.equal(res.status,status,path+' '+(res.status!==status?await res.text():''));
  return res;
};
const statusOnly=(method,body)=>({method,body,headers:{'Content-Type':'application/json'}});
assert.match(await (await check('/',200)).text(),/CampusMarket/);
const feed=await (await check('/api/listings',200)).json();
assert.equal(feed.localDemo,true,'Use a local demo server for this test.');
const invalid=new FormData();
invalid.set('title','Missing fields');
await check('/api/listings',400,{method:'POST',body:invalid});
const form=new FormData();
form.set('title','QA commuter bicycle '+Date.now());
form.set('price','120.50');
form.set('category','Bicycles');
form.set('email','qa-seller@example.test');
const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aC7sAAAAASUVORK5CYII=','base64');
form.set('photo',new Blob([Buffer.from('not a photo')],{type:'image/png'}),'invalid.png');
await check('/api/listings',400,{method:'POST',body:form});
form.set('photo',new Blob([png],{type:'image/png'}),'bike.png');
const {listing}=await (await check('/api/listings',201,{method:'POST',body:form})).json();
assert.equal(listing.price,120.5);
assert.equal(listing.seller_email,undefined);
assert.equal(listing.location,'Palo Alto, CA');
const img=await check(listing.image_url,200);
assert.equal(img.headers.get('content-type'),'image/png');
assert.deepEqual(Buffer.from(await img.arrayBuffer()),png);
const repeat=await (await check('/api/listings',200)).json();
assert.equal(repeat.listings[0].id,listing.id);
assert(!JSON.stringify(repeat).includes('qa-seller@example.test'));
const msg='/api/listings/'+listing.id+'/message';
await check(msg,400,statusOnly('POST',JSON.stringify({email:'bad',message:'Hello'})));
await check('/api/listings/00000000-0000-4000-8000-000000000000/message',404,statusOnly('POST',JSON.stringify({email:'qa-buyer@example.test',message:'Hello'})));
const reply=await (await check(msg,201,statusOnly('POST',JSON.stringify({email:'qa-buyer@example.test',message:'Is this still available?'})))).json();
assert.deepEqual(reply,{saved:true});
const record=JSON.parse(await readFile('.marketplace-local/records.json','utf8')).messages.find(m=>m.listing_id===listing.id);
assert.equal(record.seller_email,'qa-seller@example.test');
assert.equal(record.buyer_email,'qa-buyer@example.test');
await check(msg,405);
console.log('PASS: page, required fields, invalid photo, create, photo, reload, email privacy, message validation and persistence.');
